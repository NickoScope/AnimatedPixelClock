local function big(x, y, s, r, g, b)
  for i = 1, #s do
    local gl = DIG[s:sub(i, i)]
    if gl then
      for row = 1, #gl do
        local line = gl[row]
        for col = 1, #line do
          if line:sub(col, col) == "#" then px.pixel(x + col - 1, y + row - 1, r, g, b) end
        end
      end
      x = x + #gl[1] + 1
    end
  end
end

-- ---------------------------------------------------------------- draw
local DAY   = {225, 228, 232}
local NIGHT = { 52,  56,  64}

function draw()
  local n = px.now()
  local decl, sublon = sun(n)
  local sd, cd = sin(decl), cos(decl)

  px.clear(0, 0, 0)

  for r = 0, ROWS - 1 do
    local row = MASK[r + 1]
    if row then
      local lat = rad(MASK_TOP - (r + 0.5) * (MASK_TOP - MASK_BOTTOM) / ROWS)
      local sl, cl = sin(lat), cos(lat)
      for c = 0, COLS - 1 do
        if row:sub(c + 1, c + 1) == "#" then
          local lon = rad(-180 + (c + 0.5) * 360 / COLS)
          local el = deg(asin(sl * sd + cl * cd * cos(lon - sublon)))
          -- 0 at the end of civil twilight, 1 once the sun is up
          local k = max(0, min(1, (el + 6) / 6))
          px.pixel(c * 2, r * 2,
                   floor(NIGHT[1] + (DAY[1] - NIGHT[1]) * k),
                   floor(NIGHT[2] + (DAY[2] - NIGHT[2]) * k),
                   floor(NIGHT[3] + (DAY[3] - NIGHT[3]) * k))
        end
      end
    end
  end

  -- Cities are 2x2: the dot and its gap, which reads as a bigger dot on the
  -- same grid rather than as something drawn on top of it.
  for i, city in ipairs(CITIES) do
    local c, r = cell_of(city.lat, city.lon)
    local a = 1.0
    if i == 1 then a = 0.65 + 0.35 * abs(sin(pi * (n.sec + px.t() * 60))) end  -- home breathes
    px.rect(c * 2, r * 2, 2, 2, floor(255 * a), floor(140 * a), floor(40 * a), true)
  end

  big(1, 50, string.format("%02d:%02d", n.hour, n.min), 255, 255, 255)
end
