-- world_clock.lua - a dotted world map where daylight is lit and night is dim.
--
-- 128x64 divides exactly into a 64x32 grid of dots on a 2 px pitch: one lit
-- pixel, one dark gap. Land dots on the day side are bright, night-side dots
-- dim, and civil twilight (sun between 0 and -6 degrees) blends between them,
-- so the terminator draws itself and creeps across the map through the day.
--
-- The time sits in the empty South Pacific, bottom left, which on this
-- projection is the one big patch of open water with nothing to cover.

