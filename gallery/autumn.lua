local W, H = px.size()
local PI = math.pi
local TAU = PI * 2.0
local floor = math.floor
local sin = math.sin
local cos = math.cos

local seed = 0x2A1F3B7D
local function rnd()
  seed = seed ~ (seed << 13)
  seed = seed ~ (seed >> 17)
  seed = seed ~ (seed << 5)
  return (seed & 0x7FFFFFFF) / 2147483648.0
end

local leaf_colors = {
  {224, 74, 16}, {246, 118, 18}, {236, 158, 25},
  {190, 45, 12}, {166, 78, 18}, {242, 188, 48},
  {128, 51, 17}, {214, 100, 20}
}

local leaves = {}
for n = 1, 54 do
  local depth = rnd()
  leaves[n] = {
    x = rnd() * W,
    y = rnd() * 76.0,
    phase = rnd() * TAU,
    sway = 2.0 + rnd() * 7.0,
    cycles = 1 + floor(rnd() * 3.0),
    flutter = 2 + floor(rnd() * 5.0),
    depth = depth,
    size = depth > 0.68 and 2 or 1,
    color = 1 + floor(rnd() * #leaf_colors)
  }
end

local stars = {}
for n = 1, 14 do
  stars[n] = {floor(rnd() * W), floor(2 + rnd() * 22), rnd() * TAU}
end

local far_trees = {}
local x = -3
while x < W + 6 do
  local h = 5 + floor(rnd() * 9)
  far_trees[#far_trees + 1] = {x, h, 2 + floor(rnd() * 4)}
  x = x + 3 + floor(rnd() * 4)
end

local mid_trees = {}
x = -5
while x < W + 8 do
  local h = 8 + floor(rnd() * 12)
  mid_trees[#mid_trees + 1] = {x, h, 3 + floor(rnd() * 5)}
  x = x + 5 + floor(rnd() * 6)
end

local crown_dots = {}
for n = 1, 64 do
  local side = rnd() < 0.5 and -1 or 1
  crown_dots[n] = {
    side,
    floor(rnd() * 15),
    floor(rnd() * 18),
    1 + floor(rnd() * 2),
    1 + floor(rnd() * #leaf_colors)
  }
end

-- Dense precomputed micro-detail atlas is appended below.  It is data rather
-- than per-frame construction, keeping the draw loop comfortably bounded.
local detail_atlas = {}

local function hill(ybase, amp, step, shift, r, g, b)
  local lastx = -step
  local lasty = ybase
  for xx = -step, W + step, step do
    local yy = ybase + floor(sin((xx + shift) * 0.075) * amp + sin((xx + shift) * 0.031) * amp * 0.55)
    px.line(lastx, lasty, xx, yy, r, g, b)
    if xx >= 0 then
      px.rect(xx, yy, step + 1, H - yy, r, g, b, true)
    end
    lastx, lasty = xx, yy
  end
end

local function conifer(cx, ground, h, halfw, r, g, b)
  px.rect(cx, ground - 2, 1, 3, floor(r * 0.55), floor(g * 0.45), floor(b * 0.35), true)
  local top = ground - h
  for yy = top, ground - 2, 2 do
    local q = (yy - top) / h
    local hw = floor(1 + q * halfw)
    px.line(cx - hw, yy + 2, cx, yy, r, g, b)
    px.line(cx, yy, cx + hw, yy + 2, r, g, b)
  end
end

local function bare_tree(cx, ground, scale, t)
  local bend = sin(TAU * t + cx * 0.17) * 0.8
  local topx = floor(cx + bend)
  local topy = ground - 25 * scale
  local tr = floor(45 + scale * 24)
  local tg = floor(27 + scale * 12)
  local tb = floor(18 + scale * 6)
  px.line(cx, ground, topx, floor(topy), tr, tg, tb)
  px.line(cx + 1, ground, topx + 1, floor(topy + 3), tr, tg, tb)
  local by1 = floor(ground - 14 * scale)
  local by2 = floor(ground - 20 * scale)
  px.line(topx, by1, floor(cx - 10 * scale + bend), floor(ground - 26 * scale), tr, tg, tb)
  px.line(topx, by1, floor(cx + 10 * scale + bend), floor(ground - 25 * scale), tr, tg, tb)
  px.line(topx, by2, floor(cx - 5 * scale + bend), floor(ground - 31 * scale), tr, tg, tb)
  px.line(floor(cx - 5 * scale + bend), floor(ground - 21 * scale), floor(cx - 13 * scale + bend), floor(ground - 24 * scale), tr, tg, tb)
  px.line(floor(cx + 6 * scale + bend), floor(ground - 20 * scale), floor(cx + 14 * scale + bend), floor(ground - 22 * scale), tr, tg, tb)
end

local function crown(cx, cy, scale, t)
  for n = 1, #crown_dots do
    local d = crown_dots[n]
    local dx = d[1] * d[2] * scale
    local dy = d[3] * scale
    local breeze = sin(TAU * t + d[2] * 0.41 + d[3]) * (0.35 + dy * 0.025)
    local c = leaf_colors[d[5]]
    local rr = floor(c[1] * 0.72)
    local gg = floor(c[2] * 0.72)
    local bb = floor(c[3] * 0.72)
    px.circle(floor(cx + dx + breeze), floor(cy + dy * 0.46), floor(d[4] * scale), rr, gg, bb, true)
  end
  for n = 1, #detail_atlas do
    local d = detail_atlas[n]
    if d[1] <= floor(scale * 10) then
      local c = leaf_colors[d[5]]
      local sway = floor(sin(TAU * t * d[6] + d[7]) * d[4])
      px.pixel(floor(cx + d[2] * scale + sway), floor(cy + d[3] * scale),
        floor(c[1] * d[8]), floor(c[2] * d[8]), floor(c[3] * d[8]))
    end
  end
end

local function falling_leaf(l, t)
  local travel = 76.0 * l.cycles
  local yy = ((l.y + travel * t) % 76.0) - 7.0
  local sway = sin(TAU * (l.flutter * t) + l.phase) * l.sway
  local gust = sin(TAU * t) * (2.0 + 3.0 * l.depth)
  local xx = (l.x + sway + gust + W) % W
  local turn = sin(TAU * (l.flutter + 1) * t + l.phase)
  local c = leaf_colors[l.color]
  local shade = 0.56 + l.depth * 0.44
  local r = floor(c[1] * shade)
  local g = floor(c[2] * shade)
  local b = floor(c[3] * shade)
  local ix, iy = floor(xx), floor(yy)
  if l.size == 2 then
    if turn > 0.35 or turn < -0.35 then
      px.line(ix - 1, iy, ix + 1, iy, r, g, b)
      px.pixel(ix, iy + 1, floor(r * 0.65), floor(g * 0.65), floor(b * 0.65))
    else
      px.line(ix, iy - 1, ix, iy + 1, r, g, b)
    end
  else
    px.pixel(ix, iy, r, g, b)
  end
end

local function fog_band(y, drift, alpha)
  for xx = -20, W + 20, 8 do
    local wave = floor(sin((xx + drift) * 0.12) * 2.0)
    local width = 6 + floor(3.0 + 3.0 * sin((xx + drift) * 0.071))
    for yy = 0, 2 do
      px.blend(floor(xx + drift), y + wave + yy, 174, 124, 93, alpha * (1.0 - yy * 0.22))
      px.blend(floor(xx + drift + width), y + wave + yy, 192, 139, 103, alpha * 0.55)
    end
  end
end

function draw()
  local t = px.t()
  px.clear(18, 8, 18)

  local sky = {
    {0, 7, 24, 11, 34}, {7, 7, 38, 16, 45},
    {14, 7, 62, 23, 48}, {21, 7, 91, 34, 49},
    {28, 7, 130, 50, 43}, {35, 7, 173, 71, 37},
    {42, 6, 207, 103, 43}
  }
  for n = 1, #sky do
    local s = sky[n]
    px.rect(0, s[1], W, s[2], s[3], s[4], s[5], true)
  end

  for n = 1, #stars do
    local s = stars[n]
    local twinkle = 0.5 + 0.5 * sin(TAU * t * 3.0 + s[3])
    if twinkle > 0.72 then
      px.pixel(s[1], s[2], floor(116 * twinkle), floor(82 * twinkle), floor(91 * twinkle))
    end
  end

  local breathe = 0.84 + 0.12 * sin(TAU * t * 2.0)
  px.glow(101.0, 34.0, 13.0 + 1.2 * sin(TAU * t), 255, 101, 35, 0.46 * breathe)
  px.circle(101, 34, 5, 242, 126, 52, true)
  px.circle(100, 33, 3, 255, 176, 75, true)

  local far_shift = floor(3.0 * sin(TAU * t))
  hill(39, 3, 4, far_shift, 78, 39, 43)
  hill(44, 4, 4, floor(-5.0 * sin(TAU * t)), 65, 35, 31)

  for n = 1, #far_trees do
    local tr = far_trees[n]
    conifer(tr[1] + far_shift, 47, tr[2], tr[3], 62, 39, 35)
  end

  local mid_shift = floor(2.0 * sin(TAU * t + 1.8))
  hill(49, 3, 4, mid_shift, 48, 31, 25)
  for n = 1, #mid_trees do
    local tr = mid_trees[n]
    conifer(tr[1] + mid_shift, 53, tr[2], tr[3], 48, 37, 27)
  end

  px.rect(0, 51, W, 13, 38, 28, 22, true)
  for yy = 52, 63, 3 do
    local shimmer = floor(7.0 * sin(TAU * t * 2.0 + yy * 0.7))
    px.line(72 + shimmer, yy, 115 - shimmer, yy, 111, 58, 31)
    px.line(84 - shimmer, yy + 1, 106 + shimmer, yy + 1, 157, 78, 35)
  end
  for xx = 0, W - 1, 5 do
    local edge = 51 + floor(2.0 * sin(xx * 0.31 + TAU * t))
    px.pixel(xx, edge, 89, 59, 34)
  end

  fog_band(44, (t * 32.0) % 8.0, 0.26)
  fog_band(49, -((t * 24.0) % 8.0), 0.18)

  bare_tree(18, 63, 1.0, t)
  crown(18, 28, 1.0, t)
  bare_tree(119, 63, 0.75, t)
  crown(119, 36, 0.72, t)

  for n = 1, #leaves do
    falling_leaf(leaves[n], t)
  end

  local now = px.now()
  local stamp = string.format("%02d:%02d", now.hour, now.min)
  local tw = px.width(stamp)
  px.rect(W - tw - 4, 2, tw + 3, 8, 28, 13, 25, true)
  px.text(W - tw - 2, 3, stamp, 246, 190, 103)
end

