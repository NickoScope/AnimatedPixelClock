// Picopixel with one glyph corrected. Shared by every page that draws
// small text: the flight board and the yacht radar.
//
// WHY. Picopixel's stock 'U' is 'V' with one extra #.# row: both end in a
// centred pixel, so at 2 mm pitch across a room ZURICH reads ZVRICH and
// EDINBURGH reads EDINBVRGH. That is the same failure that took TomThumb out
// of the running (its M and N differ by one pixel), and live Nice data hits it
// on roughly a quarter of destination rows.
//
// FIX. Give 'U' a flat bottom, which is the form Org_01 uses at 5 px wide:
//
//     stock      corrected
//     # . #      # . #
//     # . #      # . #
//     # . #      # . #
//     # . #      # . #
//     . # .      # # #
//
// Two bits set in the bitmap; the glyph table is the stock one, reused as-is,
// so metrics (w 3, advance 4) are untouched and layout maths does not move.
// Verified by decoding the shipped header with drawChar's own bit order and
// confirming every other glyph is byte-for-byte identical.
//
// Source font: Adafruit GFX Library, Fonts/Picopixel.h - Picopixel by
// Sebastian Weber. BSD licence, same as the rest of Adafruit GFX.

